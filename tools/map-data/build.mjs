// Generates src/Dialed.UI/Components/WorldMapLand.cs (the world outline) and CountryShapes.cs (one shape per country in CountryCatalog, plus all other
// countries in one path). Source: Natural Earth through the world-atlas package (public domain). Same projection as WorldMapProjection.cs.
// Usage: npm install && npm run build   (then run the UI tests, they check that every catalog country has a shape).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { geoEquirectangular, geoPath } from 'd3-geo';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const read = (name) => JSON.parse(readFileSync(here(`node_modules/world-atlas/${name}`), 'utf8'));
const W = 1000, TOP = 75, BOTTOM = -58, H = (TOP - BOTTOM) / 360 * W;
const short = (d) => d.replace(/(\d+\.\d)\d+/g, '$1');
const projection = () => geoEquirectangular().scale(W / (2 * Math.PI)).translate([W / 2, TOP / 360 * W]).clipExtent([[0, 0], [W, H]]);

// ---- World land (1:110m) ----------------------------------------------------------------------------------------------------------------------
const land = read('land-110m.json');
const landPath = short(geoPath(projection().precision(0.1))(feature(land, land.objects.land)));
writeFileSync(here('../../src/Dialed.UI/Components/WorldMapLand.cs'),
  `namespace Dialed.UI.Components;\n\n/// <summary>The land outline for <see cref="OriginMap"/>: Natural Earth land, 1:110m (public domain), through the projection in <c>WorldMapProjection</c>. Bundled so the map needs no request. Generated by tools/map-data.</summary>\ninternal static class WorldMapLand\n{\n    public const string Path = "${landPath}";\n}\n`);

// ---- Countries (1:50m, simplified) ------------------------------------------------------------------------------------------------------------
let topo = presimplify(read('countries-50m.json'));
topo = simplify(topo, quantile(topo, Number(process.env.KEEP ?? 0.3)));
const countries = feature(topo, topo.objects.countries);
const proj = projection().clipExtent([[-5, -5], [W + 5, H + 5]]);
const path = geoPath(proj);
// Names in the catalog that Natural Earth spells differently.
const alias = { 'Democratic Republic of the Congo': 'Dem. Rep. Congo', 'Ivory Coast': "Côte d'Ivoire", 'Dominican Republic': 'Dominican Rep.', 'United States': 'United States of America', 'Central African Republic': 'Central African Rep.', 'Congo (Republic)': 'Congo' };
// Countries made of far-apart pieces: the zoom looks at this window (west, south, east, north in degrees) instead of the bounding box.
const window_ = { US: [-125, 24, -66, 50], FR: [-5, 41, 10, 51.5], NL: [3, 50.7, 7.3, 53.6], ES: [-9.5, 36, 3.5, 43.8], ID: [95, -11, 141, 6], PT: [-9.6, 36.9, -6.1, 42.2], NZ: [166, -47.5, 178.6, -34] };
const catalog = readFileSync(here('../../src/Dialed.Domain/Geography/CountryCatalog.cs'), 'utf8');
const mine = [...catalog.matchAll(/new\("([^"]+)", "(\w\w)"/g)].map((m) => [m[1], m[2]]);
const used = new Set(); const entries = [];
for (const [name, iso] of mine) {
  const f = countries.features.find((x) => x.properties.name === (alias[name] ?? name));
  if (!f) { console.warn('no polygon for', name); continue; }
  used.add(f);
  const bounds = window_[iso] ? [proj([window_[iso][0], window_[iso][3]]), proj([window_[iso][2], window_[iso][1]])] : path.bounds(f);
  entries.push({ iso, d: short(path(f)), x0: bounds[0][0], y0: bounds[0][1], x1: bounds[1][0], y1: bounds[1][1] });
}
const others = short(countries.features.filter((f) => !used.has(f)).map((f) => path(f)).filter(Boolean).join(''));
let cs = `namespace Dialed.UI.Components;\n\n/// <summary>Country outlines for the zoomed view of <see cref="OriginMap"/>: Natural Earth 1:50m (public domain) through the projection in <c>WorldMapProjection</c>, one path per country in the catalog plus one for every other country. Generated by tools/map-data; bundled so the map needs no request.</summary>\ninternal static class CountryShapes\n{\n    public sealed record Shape(string Path, double X0, double Y0, double X1, double Y1);\n\n    public static IReadOnlyDictionary<string, Shape> ByIso2 { get; } = new Dictionary<string, Shape>\n    {\n`;
for (const e of entries) cs += `        ["${e.iso}"] = new("${e.d}", ${e.x0.toFixed(1)}, ${e.y0.toFixed(1)}, ${e.x1.toFixed(1)}, ${e.y1.toFixed(1)}),\n`;
cs += `    };\n\n    public const string Others = "${others}";\n}\n`;
writeFileSync(here('../../src/Dialed.UI/Components/CountryShapes.cs'), cs);
console.log(`world ${landPath.length} chars, ${entries.length} countries (${entries.reduce((s, e) => s + e.d.length, 0)} chars), others ${others.length} chars`);
